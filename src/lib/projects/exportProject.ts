import JSZip from "jszip";
import { parseFileMarkers } from "@/lib/preview/parseFileMarkers";

const safePath = (path: string) => {
  const normalized = path.replace(/\\/g, "/").replace(/^\/+/, "");
  if (normalized.split("/").some((segment) => segment === "..")) return null;
  return normalized;
};

export function getExportFiles(code: string): Record<string, string> {
  const parsed = parseFileMarkers(code);
  if (!parsed) {
    const cleaned = code
      .replace(/<script[^>]*>[\s\S]*?__appigen[\s\S]*?<\/script>/gi, "")
      .replace(/^\s*ReactDOM\s*\.\s*createRoot\([\s\S]*?\.render\([\s\S]*?\)\s*;?\s*$/gm, "")
      .trim();
    return { "src/App.jsx": cleaned };
  }

  const files: Record<string, string> = {};
  for (const [path, content] of Object.entries(parsed.files)) {
    const safe = safePath(path);
    if (!safe || safe.endsWith(".html") && safe === "index.html") continue;
    files[safe] = content
      .replace(/<script[^>]*>[\s\S]*?__appigen[\s\S]*?<\/script>/gi, "")
      .replace(/^\s*ReactDOM\s*\.\s*createRoot\([\s\S]*?\.render\([\s\S]*?\)\s*;?\s*$/gm, "")
      .trim();
  }
  if (!files["src/App.jsx"] && !files["src/App.tsx"] && !files["src/main.jsx"]) {
    files["src/App.jsx"] = "export default function App() { return <main className=\"p-8\">App</main>; }";
  }
  return files;
}

export async function createRunnableProjectZip({ title, prompt, code }: { title: string; prompt: string; code: string }) {
  const zip = new JSZip();
  const files = getExportFiles(code);
  const exportRoot = zip.folder(title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "appigen-app");
  if (!exportRoot) throw new Error("Could not create the project archive.");

  Object.entries(files).forEach(([path, contents]) => exportRoot.file(path, contents));
  if (!files["src/main.jsx"]) {
    exportRoot.file("src/main.jsx", `import React from "react";\nimport { createRoot } from "react-dom/client";\nimport App from "./App.jsx";\nimport "./styles.css";\n\ncreateRoot(document.getElementById("root")).render(<App />);\n`);
  }
  exportRoot.file("src/styles.css", "@tailwind base;\n@tailwind components;\n@tailwind utilities;\n");
  exportRoot.file("index.html", "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"UTF-8\"/><meta name=\"viewport\" content=\"width=device-width,initial-scale=1.0\"/><title>AppiGen app</title></head><body><div id=\"root\"></div><script type=\"module\" src=\"/src/main.jsx\"></script></body></html>\n");
  exportRoot.file("package.json", JSON.stringify({
    name: "appigen-generated-app",
    private: true,
    version: "1.0.0",
    type: "module",
    scripts: { dev: "vite", build: "vite build", preview: "vite preview" },
    dependencies: { "@vitejs/plugin-react": "4.3.4", "lucide-react": "0.468.0", react: "18.3.1", "react-dom": "18.3.1", vite: "6.0.5" },
    devDependencies: { autoprefixer: "10.4.20", postcss: "8.4.49", tailwindcss: "3.4.16" },
  }, null, 2));
  exportRoot.file("vite.config.js", "import { defineConfig } from 'vite';\nimport react from '@vitejs/plugin-react';\nexport default defineConfig({ plugins: [react()] });\n");
  exportRoot.file("tailwind.config.js", "export default { content: ['./index.html', './src/**/*.{js,jsx}'], theme: { extend: {} }, plugins: [] };\n");
  exportRoot.file("postcss.config.js", "export default { plugins: { tailwindcss: {}, autoprefixer: {} } };\n");
  exportRoot.file("README.md", `# ${title}\n\nGenerated by AppiGen Studio.\n\n## Original prompt\n${prompt || "No prompt saved."}\n\n## Run locally\n\`\`\`sh\nnpm install\nnpm run dev\n\`\`\`\n`);
  return zip.generateAsync({ type: "blob" });
}